"""Exhaustive state-space exploration over the payment/subscription lifecycle.

WHY THIS FILE EXISTS
---------------------
modules/state_transition_consistency.py already defines the lifecycle as an
explicit graph (VALID_PAYMENT_TRANSITIONS / VALID_SUBSCRIPTION_TRANSITIONS)
and already tests it -- but only by hand-picking a small number of specific
cases: exactly two illegal transitions (STATE-002: subscription
cancelled->active, payment refunded->captured) and exactly one concurrent
race (STATE-001: cancel-vs-refund on a freshly created payment). That module
is not wrong; it is SPECIFIED, in the sense every axis-1 case in this
project's own brief is specified: someone picked the two illegal
transitions and the one race they considered most realistic and wrote a
test for each.

This module answers a different question: given the SAME graph, what does
EVERY illegal transition and EVERY pairwise race actually look like, not
just the ones someone thought to write down? The graph is small and finite,
so this is not a heuristic search -- it is exhaustive enumeration, and the
result is a complete, checkable set: "these are all of them" is a true
statement about the modeled graph, not an estimate. See
`docs/state_exploration_findings.md` (generated by
scripts/run_state_exploration.py) for the concrete numbers this produces
against the graph as it stands today, and exactly which of them the
hand-written module already covers.

Deliberately has ZERO dependency on pydantic/httpx/the HTTP layer: it
imports only the two plain `dict[str, set[str]]` transition tables from
app.testing.lifecycle_model (itself dependency-free -- see that module's
docstring for why the tables live there and not in
state_transition_consistency.py, which still owns them conceptually and
re-exports them unchanged) and otherwise uses stdlib only. That is what
makes it possible
to exhaustively verify this module's own claims (reachability is correct,
enumeration is complete, no pair is silently skipped) with nothing but the
Python interpreter -- no network, no test framework, no live target -- and
it is why this file, unlike a module that sends HTTP requests, can be
imported and run standalone in an environment where fastapi/httpx/pydantic
are not installed at all.

Turning a finding from this module into an actual HTTP request against a
real target (which operation reaches which state) is a SEPARATE, later
step -- NOT YET BUILT as of this pass; it needs a live target and the
httpx/pydantic stack this sandbox does not have, so it is scoped as
follow-up work rather than written un-verified. It would live at
modules/state_machine_exploration.py, as a BaseTestModule following the
exact conventions state_transition_consistency.py already establishes
(EndpointMap-driven request building, execute_case, TestResult
emission) -- see the project's before/after report for the precise scope
of what this module (pure graph algorithms, fully verified standalone)
does and does not yet close the loop on. That mapping is target-specific
domain knowledge (which endpoint reaches "captured"?) that does not
belong in a pure graph algorithm regardless of when it gets written.
"""
from __future__ import annotations

from dataclasses import dataclass
from itertools import combinations
from typing import Mapping

from app.testing.lifecycle_model import (
    VALID_PAYMENT_TRANSITIONS,
    VALID_SUBSCRIPTION_TRANSITIONS,
)

TransitionMap = Mapping[str, "set[str]"]


@dataclass(frozen=True)
class IllegalTransition:
    """A (from, to) pair that is NOT in the modeled transition table for
    this resource type -- i.e. an operation the system under test should
    reject if attempted from `from_state`."""

    resource_type: str
    from_state: str
    to_state: str

    @property
    def id(self) -> str:
        return f"{self.resource_type}:{self.from_state}->{self.to_state}"


@dataclass(frozen=True)
class ConcurrentRace:
    """Two DISTINCT legal next-states reachable from the same current
    state -- i.e. two operations that could both be attempted on the same
    resource while it sits in `from_state`. Firing both at once is exactly
    the STATE-001-style race, generalized to every state that has more
    than one legal exit, not just the one state someone picked by hand."""

    resource_type: str
    from_state: str
    operation_a: str  # target state of the first operation
    operation_b: str  # target state of the second operation

    @property
    def id(self) -> str:
        return f"{self.resource_type}:{self.from_state}=={self.operation_a}/{self.operation_b}"


@dataclass(frozen=True)
class ExplorationResult:
    resource_type: str
    all_states: frozenset[str]
    reachable_states: frozenset[str]
    unreachable_states: frozenset[str]
    legal_transition_count: int
    illegal_transitions: tuple[IllegalTransition, ...]
    concurrent_races: tuple[ConcurrentRace, ...]

    @property
    def total_ordered_pairs(self) -> int:
        n = len(self.all_states)
        return n * (n - 1)

    def to_dict(self) -> dict:
        return {
            "resource_type": self.resource_type,
            "all_states": sorted(self.all_states),
            "reachable_states": sorted(self.reachable_states),
            "unreachable_states": sorted(self.unreachable_states),
            "legal_transition_count": self.legal_transition_count,
            "illegal_transition_count": len(self.illegal_transitions),
            "concurrent_race_count": len(self.concurrent_races),
            "illegal_transitions": [t.id for t in self.illegal_transitions],
            "concurrent_races": [r.id for r in self.concurrent_races],
        }


def _all_states(transitions: TransitionMap) -> set[str]:
    """Every state mentioned anywhere in the table, as a source OR a
    target -- a purely-terminal state (empty value set) still needs to
    appear here, and does, because it is present as a KEY with value
    set() in both VALID_*_TRANSITIONS tables. Included defensively in case
    a future edit adds a target state that is never used as a key."""
    states = set(transitions.keys())
    for targets in transitions.values():
        states |= targets
    return states


def reachable_states(transitions: TransitionMap, start: str) -> frozenset[str]:
    """BFS reachability closure from `start`: every state reachable via
    zero or more legal transitions, including `start` itself. Exhaustive
    by construction -- a breadth-first traversal of a finite graph visits
    every reachable node exactly once; there is no sampling here."""
    seen = {start}
    frontier = [start]
    while frontier:
        next_frontier: list[str] = []
        for state in frontier:
            for target in transitions.get(state, ()):
                if target not in seen:
                    seen.add(target)
                    next_frontier.append(target)
        frontier = next_frontier
    return frozenset(seen)


def enumerate_illegal_transitions(transitions: TransitionMap, resource_type: str) -> tuple[IllegalTransition, ...]:
    """Every (from, to) pair over ALL states in the table where `to` is
    not in the legal target set for `from` -- the complement of the
    modeled relation, restricted to modeled states. This is what "attempt
    every transition nobody said was fine" means when the state space is
    small enough to do it exactly rather than by sampling."""
    states = sorted(_all_states(transitions))
    found = []
    for frm in states:
        legal = transitions.get(frm, set())
        for to in states:
            if to == frm:
                continue
            if to not in legal:
                found.append(IllegalTransition(resource_type, frm, to))
    return tuple(found)


def enumerate_concurrent_races(transitions: TransitionMap, resource_type: str) -> tuple[ConcurrentRace, ...]:
    """Every unordered pair of distinct legal next-states from the same
    current state -- every point in the graph where two operations could
    plausibly be in flight on the same resource at once. A state with N
    legal exits contributes C(N,2) races; a terminal or single-exit state
    contributes none (there is nothing to race against)."""
    found = []
    for frm in sorted(transitions.keys()):
        targets = sorted(transitions.get(frm, set()))
        if len(targets) < 2:
            continue
        for a, b in combinations(targets, 2):
            found.append(ConcurrentRace(resource_type, frm, a, b))
    return tuple(found)


def explore(transitions: TransitionMap, resource_type: str, start_states: tuple[str, ...]) -> ExplorationResult:
    """Runs the full exhaustive analysis for one resource type's transition
    table. `start_states` are the state(s) a freshly-created resource of
    this type can begin in (a resource type can have more than one valid
    entry point; the reachable set is the union over all of them)."""
    all_states = frozenset(_all_states(transitions))
    reachable: set[str] = set()
    for start in start_states:
        reachable |= reachable_states(transitions, start)
    unreachable = all_states - reachable

    legal_count = sum(len(targets) for targets in transitions.values())
    illegal = enumerate_illegal_transitions(transitions, resource_type)
    races = enumerate_concurrent_races(transitions, resource_type)

    return ExplorationResult(
        resource_type=resource_type,
        all_states=all_states,
        reachable_states=frozenset(reachable),
        unreachable_states=frozenset(unreachable),
        legal_transition_count=legal_count,
        illegal_transitions=illegal,
        concurrent_races=races,
    )


def explore_payment() -> ExplorationResult:
    return explore(VALID_PAYMENT_TRANSITIONS, "payment", start_states=("pending",))


def explore_subscription() -> ExplorationResult:
    return explore(VALID_SUBSCRIPTION_TRANSITIONS, "subscription", start_states=("trialing",))


def diff_against_hand_written(
    exploration: ExplorationResult,
    *,
    hand_written_illegal: frozenset[tuple[str, str]],
    hand_written_races: frozenset[tuple[str, str, str]],
) -> dict:
    """Compares an exhaustive result against the (from, to) pairs and
    (from, a, b) race triples that modules/state_transition_consistency.py
    already tests by hand, so "how much of this is genuinely new coverage"
    is a computed fact, not an estimate. Callers pass the hand-written sets
    explicitly (rather than this module trying to parse them out of the
    other module's source) so the comparison stays correct even if the
    hand-written cases change -- the caller is expected to keep this list
    in sync with STATE-002's `unusual_transitions` and STATE-001's actual
    pair, and scripts/run_state_exploration.py's own header comment says so.
    """
    new_illegal = [
        t for t in exploration.illegal_transitions if (t.from_state, t.to_state) not in hand_written_illegal
    ]
    new_races = [
        r
        for r in exploration.concurrent_races
        if (r.from_state, r.operation_a, r.operation_b) not in hand_written_races
        and (r.from_state, r.operation_b, r.operation_a) not in hand_written_races
    ]
    return {
        "resource_type": exploration.resource_type,
        "hand_written_illegal_count": len(hand_written_illegal),
        "exhaustive_illegal_count": len(exploration.illegal_transitions),
        "new_illegal_count": len(new_illegal),
        "new_illegal": [t.id for t in new_illegal],
        "hand_written_race_count": len(hand_written_races),
        "exhaustive_race_count": len(exploration.concurrent_races),
        "new_race_count": len(new_races),
        "new_races": [r.id for r in new_races],
    }
