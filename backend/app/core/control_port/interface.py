"""Static interface of the Control Adapter. The Main System types against these protocols only (never against ``enterprise_controls``).

Every method corresponds to an audited call site of the Main System (see MIGRATION_MAP.md §1.4, A1–A17); a control without a Main-System
caller has no adapter method. Both implementations satisfy it: ``EnterpriseControlAdapter`` (delegation, normal operation) and
``FailOpenControlAdapter`` (availability mode when the Enterprise Controls are not available).
"""
from __future__ import annotations

from typing import Any, Iterable, Mapping, Protocol

from app.core.control_port.contract import ConfirmationCandidate, EvidenceArtifact, GateDecision, Reason


class ScopePolicyView(Protocol):
    """What the Main System may read from a scope policy."""

    allowed_hosts: tuple[str, ...]
    allowed_schemes: tuple[str, ...]
    max_requests: int
    max_requests_per_second: float
    burst: int
    deadline_seconds: float | None
    max_redirects: int

    def to_dict(self) -> dict[str, Any]: ...


class RunGuard(Protocol):
    """Per-run request guard (A4): the surface ``QAHttpClient``, ``TestRunner`` and the engine use."""

    @property
    def policy(self) -> ScopePolicyView: ...
    @property
    def killed(self) -> bool: ...
    @property
    def kill_reason(self) -> str: ...
    @property
    def requests_used(self) -> int: ...
    @property
    def remaining_budget(self) -> int: ...

    def start(self) -> None: ...
    def kill(self, reason: str = "kill switch engaged") -> None: ...
    def stop_reason(self) -> str | None: ...
    def check_url(self, url: str, probe_class: str | None = None) -> None: ...
    def preflight(self, url: str, probe_class: str | None = None) -> None: ...
    async def acquire(self, url: str, method: str = "GET", probe_class: str | None = None) -> None: ...
    def stats(self) -> dict[str, Any]: ...


class EvidenceLedgerHandle(Protocol):
    """Evidence admission store (A9)."""

    authorization_ref: str

    @property
    def accepted(self) -> dict[str, EvidenceArtifact]: ...
    @property
    def rejected(self) -> list[dict[str, Any]]: ...

    def protect(self, *values: str) -> None: ...
    def register_identity(self, alias: str, tenant_alias: str | None = None) -> None: ...
    def validate(self, artifact: EvidenceArtifact | None) -> list[Reason]: ...
    def try_admit(self, artifact: EvidenceArtifact | None) -> tuple[bool, list[Reason]]: ...
    def admit(self, artifact: EvidenceArtifact | None) -> EvidenceArtifact: ...
    async def flush_pending(self) -> None: ...
    def is_admitted(self, artifact_id: str) -> bool: ...
    def ids(self) -> list[str]: ...
    def summary(self) -> dict[str, Any]: ...


class ConfirmationGateHandle(Protocol):
    """Confirmation decision (A11). A returned token (``GateDecision.token``) answers ``covers(hypothesis_id)``."""

    def evaluate(self, candidate: ConfirmationCandidate) -> GateDecision: ...


class ControlAdapter(Protocol):
    mode: str  # "enterprise" | "fail_open"

    def status(self) -> dict[str, Any]: ...

    # A1-A3 run admission and scope
    def validate_run_inputs(
        self, *, custom_headers: Mapping[str, str] | None = None, session_cookies: Mapping[str, str] | None = None,
        endpoint_overrides: Mapping[str, Any] | None = None, extra_allowed_hosts: Iterable[str] = (), integrity_brief: Mapping[str, Any] | None = None,
    ) -> None: ...
    def build_scope_policy(self, environment_url: str, extra_hosts: Iterable[str] = (), **overrides: Any) -> ScopePolicyView: ...
    def create_run_guard(self, policy: ScopePolicyView, *, clock: Any = ..., sleep: Any = ...) -> RunGuard: ...

    # A5 probe bodies
    def withhold_body(self, body: Any) -> Any: ...
    def body_size(self, body: Any) -> int: ...

    # A6-A8 execution brief
    def load_brief(self, path: str) -> dict[str, Any] | None: ...
    def parse_brief(self, data: Mapping[str, Any], *, env: Mapping[str, str] | None = None, tokens: Mapping[str, str] | None = None) -> Any: ...
    def host_permitted(self, base_url: str, allowed_hosts: Iterable[str]) -> bool: ...

    # A9-A13 evidence, confirmation, blindness
    def new_evidence_ledger(self, *, authorization_ref: str, approved_identity_aliases: Iterable[str] = (), approved_tenant_aliases: Iterable[str] = ()) -> EvidenceLedgerHandle: ...
    def build_artifact(self, **fields: Any) -> EvidenceArtifact: ...
    def new_confirmation_gate(self, ledger: EvidenceLedgerHandle) -> ConfirmationGateHandle: ...
    def scrub_headers(self, headers: Mapping[str, Any] | None) -> tuple[dict[str, str], list[str]]: ...
    def scrub_body(self, body: Any) -> tuple[Any, list[str]]: ...
    def filter_label_channel(self, records: Any) -> tuple[Any, int]: ...

    # A14-A16 API perimeter, provider/provenance rules, quarantine
    def install_http_perimeter(self, app: Any, *, allowed_hostnames: Iterable[str], extra_allowed_origins: Iterable[str], allow_null_origin: bool, api_token: str | None) -> bool: ...
    def is_provider_facing_operation(self, operation: str) -> bool: ...
    def is_allowed_observed_via(self, value: str) -> bool: ...
    def refuse_in_pure_mode(self, module_name: str) -> None: ...
